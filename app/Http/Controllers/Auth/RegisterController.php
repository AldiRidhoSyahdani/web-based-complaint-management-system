<?php

namespace App\Http\Controllers\Auth;

use App\Http\Controllers\Controller;
use App\Providers\RouteServiceProvider;
use App\Models\User;
use Illuminate\Foundation\Auth\RegistersUsers;
use Illuminate\Support\Facades\Hash;
use Illuminate\Support\Facades\Validator;

class RegisterController extends Controller
{
    use RegistersUsers;

    // Setelah daftar → redirect ke login (bukan home)
    protected $redirectTo = '/login';

    public function __construct()
    {
        $this->middleware('guest');
    }

    protected function validator(array $data)
    {
        return Validator::make($data, [
            'name' => ['required', 'string', 'max:255'],
            'email' => ['required', 'string', 'email', 'max:255', 'unique:users'],
            'password' => ['required', 'string', 'min:8', 'confirmed'],
        ]);
    }

    protected function create(array $data)
    {
        return User::create([
            'name' => $data['name'],
            'email' => $data['email'],
            'password' => Hash::make($data['password']),
        ]);
    }

    // OVERRIDE METHOD INI — INI YANG BIKIN TIDAK AUTO-LOGIN
    protected function registered(\Illuminate\Http\Request $request, $user)
    {
        // Kita tidak login otomatis
        // Langsung arahkan ke login dengan pesan sukses
        return redirect()->route('login')
            ->with('status', 'Pendaftaran berhasil! Silakan login dengan akun yang baru dibuat.');
    }
}